/**
 * The shell every email from this application is rendered in.
 *
 * Adapted from the organization's reference email implementation, whose
 * structure is the convention and is kept as it is. Everything in it is there
 * for Outlook 2016, which renders HTML with Word's engine, and none of it
 * should be "modernised":
 *
 *   - layout is nested tables with `cellPadding`, `cellSpacing` and `border`
 *     zeroed, never flex, grid or positioned `div`s;
 *   - the message is a fixed 620px column, set as an attribute *and* a style,
 *     because Outlook honours one and other clients the other;
 *   - every style is inline (see `BaseEmailStyles.ts`), and the one `<style>`
 *     block holds only the MSO resets and the font stack;
 *   - direction is declared on `<Html>` and again on the header tables, since
 *     Outlook does not reliably inherit it into a table;
 *   - vertical space is an empty cell or a spacer table with 1px type, which
 *     Outlook will not collapse the way it ignores margins.
 *
 * Images are `data:` URIs from `emails/images/`, generated by
 * `scripts/base64convertor.mts`, because the organization's mail environment
 * does not fetch remote images. `tohenWhite` is the organization's logo and
 * is always shown. The smaller application-logo slot beside the header label
 * is kept from the reference but renders only when a template passes
 * `logoSrc`; no application logo has been supplied.
 */

import { Body, Head, Html, Preview } from "@react-email/components";
import type { ReactNode } from "react";

import { EMAIL_LABELS } from "@/lib/labels";

import { tohenWhiteLogo } from "../images/tohenWhite";
import { colors, styles } from "./BaseEmailStyles";

export { colors, styles };

interface BaseEmailProps {
  preview?: string;
  headerLabel: string;
  title: string;
  children: ReactNode;
  logoSrc?: string;
}

export function BaseEmail({
  preview,
  headerLabel,
  title,
  children,
  logoSrc,
}: BaseEmailProps) {
  return (
    <Html lang="he" dir="rtl">
      <Head>
        <meta httpEquiv="Content-Type" content="text/html; charset=UTF-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1.0" />
        {/* Outlook 2016 MSO resets */}
        <style>{`
          table { border-collapse: collapse; mso-table-lspace: 0pt; mso-table-rspace: 0pt; }
          td { mso-line-height-rule: exactly; }
          img { border: 0; outline: none; text-decoration: none; }
          .ExternalClass { width: 100%; }
          .ExternalClass, .ExternalClass p, .ExternalClass span,
          .ExternalClass font, .ExternalClass td, .ExternalClass div { line-height: 100%; }

          body, table, td, p, a, li, span {
            font-family: Calibri, Arial, sans-serif !important;
            mso-font-charset: 0;
          }
        `}</style>
      </Head>
      {preview ? <Preview>{preview}</Preview> : null}
      <Body style={styles.body}>
        <table
          width="100%"
          cellPadding={0}
          cellSpacing={0}
          border={0}
          style={styles.outerTable}
        >
          <tbody>
            <tr>
              <td align="center">
                <table
                  width="620"
                  cellPadding={0}
                  cellSpacing={0}
                  border={0}
                  style={{ width: "620px", borderCollapse: "collapse" }}
                >
                  <tbody>
                    <tr>
                      <td style={{ padding: "32px 0 0 0" }} />
                    </tr>

                    {/* Header */}
                    <tr>
                      <td>
                        <table
                          width="100%"
                          cellPadding={0}
                          cellSpacing={0}
                          border={0}
                          dir="rtl"
                          style={styles.headerTable}
                        >
                          <tbody>
                            <tr>
                              <td dir="rtl" style={styles.headerTextCell}>
                                <table
                                  cellPadding={0}
                                  cellSpacing={0}
                                  border={0}
                                  dir="rtl"
                                  style={styles.headerSubtitleRow}
                                >
                                  <tbody>
                                    <tr>
                                      {logoSrc ? (
                                        <td style={styles.headerSubtitleLogoCell}>
                                          <img
                                            src={logoSrc}
                                            alt={EMAIL_LABELS.appLogoAlt}
                                            style={{
                                              display: "block",
                                              verticalAlign: "middle",
                                            }}
                                          />
                                        </td>
                                      ) : null}
                                      <td style={styles.headerSubtitleTextCell}>
                                        <p style={styles.headerLabel}>
                                          {headerLabel}
                                        </p>
                                      </td>
                                    </tr>
                                  </tbody>
                                </table>

                                <p style={styles.headerTitle}>{title}</p>
                              </td>

                              <td
                                style={{
                                  textAlign: "left",
                                  verticalAlign: "middle",
                                  paddingLeft: "26px",
                                }}
                              >
                                <img
                                  src={tohenWhiteLogo}
                                  alt={EMAIL_LABELS.organizationLogoAlt}
                                />
                              </td>
                            </tr>
                          </tbody>
                        </table>
                        {/* Accent bar */}
                        <table
                          width="100%"
                          cellPadding={0}
                          cellSpacing={0}
                          border={0}
                        >
                          <tbody>
                            <tr>
                              <td style={styles.accentBar} />
                            </tr>
                          </tbody>
                        </table>
                      </td>
                    </tr>

                    {/* Card body */}
                    <tr>
                      <td>
                        <table
                          width="100%"
                          cellPadding={0}
                          cellSpacing={0}
                          border={0}
                          style={styles.card}
                        >
                          <tbody>
                            <tr>
                              <td style={styles.cardInner}>{children}</td>
                            </tr>
                          </tbody>
                        </table>
                      </td>
                    </tr>

                    {/* Footer */}
                    <tr>
                      <td>
                        <table
                          width="100%"
                          cellPadding={0}
                          cellSpacing={0}
                          border={0}
                          style={styles.footer}
                        >
                          <tbody>
                            <tr>
                              <td style={styles.footerInner}>
                                <p
                                  style={{
                                    ...styles.bodyText,
                                    fontSize: "13px",
                                    color: colors.textLight,
                                    margin: "0",
                                    fontStyle: "italic",
                                  }}
                                >
                                  {EMAIL_LABELS.autoSentFooter}
                                </p>
                              </td>
                            </tr>
                          </tbody>
                        </table>
                      </td>
                    </tr>

                    <tr>
                      <td style={{ padding: "0 0 32px 0" }} />
                    </tr>
                  </tbody>
                </table>
              </td>
            </tr>
          </tbody>
        </table>
      </Body>
    </Html>
  );
}

