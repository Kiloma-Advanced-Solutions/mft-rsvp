/**
 * The shell every email from this application is rendered in.
 *
 * Adapted from the organization's reference email implementation, whose
 * structure is the convention and is kept as it is. Everything in it is there
 * for Outlook 2016, which renders HTML with Word's engine, and none of it
 * should be "modernised":
 *
 *   - layout is nested tables with `cellPadding`, `cellSpacing` and `border`
 *     zeroed, never flex, grid or positioned `div`s;
 *   - the message is a fixed 620px column, set as an attribute *and* a style,
 *     because Outlook honours one and other clients the other;
 *   - every style is inline (see `BaseEmailStyles.ts`), and the one `<style>`
 *     block holds only the MSO resets, the font stack and the narrow-screen
 *     media query, whose classes override values that are already inline;
 *   - direction is declared on `<Html>` and again on the header tables, since
 *     Outlook does not reliably inherit it into a table;
 *   - vertical space is an empty cell or a spacer table with 1px type, which
 *     Outlook will not collapse the way it ignores margins.
 *
 * The look is M11's, approved for PR 5 as "Variant C": a compact navy header
 * with the header label and the organization's logo, then a separate card
 * that opens with `title` above a divider, then the footer line under the
 * card. The title is in the card rather than the header, so a long one wraps
 * in the card instead of stretching the navy band.
 *
 * Images are `data:` URIs from `emails/images/`, generated by
 * `scripts/base64convertor.mts`, because the organization's mail environment
 * does not fetch remote images. `tohenWhite` is the organization's logo and
 * is always shown, at half size; its alt text is styled to read on the navy
 * header when a client does not show the image. The smaller application-logo
 * slot beside the header label is kept from the reference but renders only
 * when a template passes `logoSrc`; no application logo has been supplied.
 */

import { Body, Head, Html, Preview } from "@react-email/components";
import type { CSSProperties, ReactNode } from "react";

import { EMAIL_LABELS } from "@/lib/labels";

import { tohenWhiteLogo } from "../images/tohenWhite";
import { MOBILE_STYLES, styles } from "./BaseEmailStyles";

export { styles };

interface BaseEmailProps {
  preview?: string;
  headerLabel: string;
  title: string;
  children: ReactNode;
  logoSrc?: string;
}

export function BaseEmail({
  preview,
  headerLabel,
  title,
  children,
  logoSrc,
}: BaseEmailProps) {
  return (
    <Html lang="he" dir="rtl">
      <Head>
        <meta httpEquiv="Content-Type" content="text/html; charset=UTF-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1.0" />
        {/* Outlook 2016 MSO resets, then the narrow-screen media query */}
        <style>{`
          table { border-collapse: collapse; mso-table-lspace: 0pt; mso-table-rspace: 0pt; }
          td { mso-line-height-rule: exactly; }
          img { border: 0; outline: none; text-decoration: none; }
          .ExternalClass { width: 100%; }
          .ExternalClass, .ExternalClass p, .ExternalClass span,
          .ExternalClass font, .ExternalClass td, .ExternalClass div { line-height: 100%; }

          body, table, td, p, a, li, span {
            font-family: Calibri, Arial, sans-serif !important;
            mso-font-charset: 0;
          }
${MOBILE_STYLES}
        `}</style>
      </Head>
      {preview ? <Preview>{preview}</Preview> : null}
      <Body style={styles.body}>
        <table
          width="100%"
          cellPadding={0}
          cellSpacing={0}
          border={0}
          style={styles.outerTable}
        >
          <tbody>
            <tr>
              <td align="center" className="em-outer" style={styles.outerCell}>
                <table
                  width="620"
                  cellPadding={0}
                  cellSpacing={0}
                  border={0}
                  className="em-column"
                  style={styles.column}
                >
                  <tbody>
                    <tr>
                      <td className="em-top" style={styles.columnTop} />
                    </tr>

                    {/* Header */}
                    <tr>
                      <td>
                        <table
                          width="100%"
                          cellPadding={0}
                          cellSpacing={0}
                          border={0}
                          dir="rtl"
                          style={styles.headerTable}
                        >
                          <tbody>
                            <tr>
                              <td
                                dir="rtl"
                                className="em-head"
                                style={styles.headerTextCell}
                              >
                                <table
                                  cellPadding={0}
                                  cellSpacing={0}
                                  border={0}
                                  dir="rtl"
                                  style={styles.headerSubtitleRow}
                                >
                                  <tbody>
                                    <tr>
                                      {logoSrc ? (
                                        <td style={styles.headerSubtitleLogoCell}>
                                          <img
                                            src={logoSrc}
                                            alt={EMAIL_LABELS.appLogoAlt}
                                            style={{
                                              display: "block",
                                              verticalAlign: "middle",
                                            }}
                                          />
                                        </td>
                                      ) : null}
                                      <td style={styles.headerSubtitleTextCell}>
                                        <p style={styles.headerLabel}>
                                          {headerLabel}
                                        </p>
                                      </td>
                                    </tr>
                                  </tbody>
                                </table>
                              </td>

                              <td style={styles.headerLogoCell}>
                                <img
                                  src={tohenWhiteLogo}
                                  alt={EMAIL_LABELS.organizationLogoAlt}
                                  width={52}
                                  height={46}
                                  style={styles.headerLogo}
                                />
                              </td>
                            </tr>
                          </tbody>
                        </table>
                      </td>
                    </tr>

                    <tr>
                      <td style={styles.headerGap}>&nbsp;</td>
                    </tr>

                    {/* Card */}
                    <tr>
                      <td>
                        <table
                          width="100%"
                          cellPadding={0}
                          cellSpacing={0}
                          border={0}
                          style={styles.card}
                        >
                          <tbody>
                            <tr>
                              <td
                                dir="rtl"
                                className="em-pad"
                                style={styles.cardInner}
                              >
                                <p className="em-title" style={styles.title}>
                                  {title}
                                </p>
                                <Spacer height={24} />
                                <table
                                  width="100%"
                                  cellPadding={0}
                                  cellSpacing={0}
                                  border={0}
                                >
                                  <tbody>
                                    <tr>
                                      <td style={styles.divider}>&nbsp;</td>
                                    </tr>
                                  </tbody>
                                </table>
                                <Spacer height={24} />
                                {children}
                              </td>
                            </tr>
                          </tbody>
                        </table>
                      </td>
                    </tr>

                    {/* Footer */}
                    <tr>
                      <td className="em-foot" style={styles.footerCell}>
                        <p style={styles.footerText}>
                          {EMAIL_LABELS.autoSentFooter}
                        </p>
                      </td>
                    </tr>

                    <tr>
                      <td style={styles.columnBottom} />
                    </tr>
                  </tbody>
                </table>
              </td>
            </tr>
          </tbody>
        </table>
      </Body>
    </Html>
  );
}

// ─── Reusable sub-components ──────────────────────────────────────────────────
// The reference's `InfoBox` and `AlertBox` are not carried over yet: no email
// here uses them. Bring one across from the reference with its styles when one
// does.

interface DetailRowProps {
  label: string;
  value: string;
  /** Draws the divider above the row: every row but the first. */
  divided?: boolean;
}

export function DetailRow({ label, value, divided = false }: DetailRowProps) {
  const line: CSSProperties = divided ? styles.detailsRowDivider : {};
  return (
    <tr>
      <td className="em-label" style={{ ...styles.detailsLabel, ...line }}>
        {label}
      </td>
      <td className="em-value" style={{ ...styles.detailsValue, ...line }}>
        {value}
      </td>
    </tr>
  );
}

interface SpacerProps {
  height?: number;
}

export function Spacer({ height = 16 }: SpacerProps) {
  return (
    <table width="100%" cellPadding={0} cellSpacing={0} border={0}>
      <tbody>
        <tr>
          <td
            style={{
              height: `${height}px`,
              fontSize: "1px",
              lineHeight: "1px",
            }}
          >
            &nbsp;
          </td>
        </tr>
      </tbody>
    </table>
  );
}
